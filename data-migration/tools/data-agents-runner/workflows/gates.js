const path = require('node:path');
const { isoNow } = require('../lib/markdown');
const { ensureDir, fileExists, listDirs, listFiles, writeFileAtomic } = require('../lib/fsutil');

const GATE1_REQUIRED = [
  'problem-statement.md',
  'kpis.md',
  'analytical-questions.md',
  'sttm.md',
  'dq-initial.md',
];

const GATE2_REQUIRED = [
  'architecture.md',
  'data-model.md',
  'agent-blueprint.md',
  'agent-execution-contracts.md',
  'dq-rules.md',
  'monitoring-spec.md',
];

const GATE3_REQUIRED = [
  { type: 'dir', name: 'sql' },
  { type: 'dir', name: 'pyspark' },
  { type: 'dir', name: 'tests' },
  { type: 'file', name: 'README.md' },
];

async function validateGate1(ctx) {
  await ensureDir(ctx.paths.planning);
  const checks = [];
  for (const f of GATE1_REQUIRED) {
    checks.push({ item: f, ok: await fileExists(path.join(ctx.paths.planning, f)) });
  }

  const ok = checks.every((c) => c.ok);
  const reportPath = path.join(ctx.paths.planning, 'gate-1-report.md');

  const lines = [];
  lines.push('# Gate 1 Report (UP→MID)');
  lines.push('');
  lines.push(`Date: ${isoNow()}`);
  lines.push('');
  lines.push('## Checklist');
  for (const c of checks) lines.push(`${c.ok ? '✅' : '❌'} ${c.item}`);
  lines.push('');
  lines.push('## Resultado');
  lines.push(`Status: ${ok ? 'PASS' : 'FAIL'}`);
  lines.push('');
  lines.push('## Gaps');
  const gaps = checks.filter((c) => !c.ok).map((c) => c.item);
  lines.push(gaps.length ? gaps.map((g) => `- ${g}`).join('\n') : '- (none)');
  lines.push('');
  lines.push('---');
  lines.push('Generated by: gate-1-up-mid (local runner)');
  lines.push(`Date: ${isoNow()}`);
  lines.push('');

  await writeFileAtomic(reportPath, lines.join('\n'));
  return { ok, output: reportPath, checks };
}

