const fs = require('node:fs/promises');
const path = require('node:path');

/**
 * Smoke-runner (local) para validar rapidamente o módulo `data_agents`.
 *
 * - Não depende do runtime do BMAD.
 * - Cria artefatos mínimos em `{artifacts_root}/{project_code}` para simular execuções.
 *
 * Uso:
 *   node src\modules\data_agents\tools\smoke_run_workflows.js
 */

function isoNow() {
  return new Date().toISOString();
}

async function writeIfMissing(filePath, content) {
  let exists = true;
  try {
    await fs.access(filePath);
  } catch {
    exists = false;
  }
  if (!exists) {
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    await fs.writeFile(filePath, content, 'utf8');
    return { created: true };
  }
  return { created: false };
}

async function appendAudit(filePath, auditBlock) {
  try {
    await fs.access(filePath);
  } catch {
    return;
  }

  const text = await fs.readFile(filePath, 'utf8');
  if (text.includes(auditBlock.trim())) return;
  await fs.appendFile(filePath, `\n${auditBlock}\n`, 'utf8');
}

async function ensureArtifactsFolders(projectRoot, config) {
  // Mirror do installer do módulo.
  const artifactsRoot = (config?.artifacts_root || '{output_folder}').toString();
  const projectCode = (config?.project_code || 'trip-data-poc').toString();

  const normalizedArtifactsRoot = artifactsRoot.replace('{project-root}/', '');
  const basePath = path.isAbsolute(normalizedArtifactsRoot)
    ? normalizedArtifactsRoot
    : path.join(projectRoot, normalizedArtifactsRoot);

  const target = path.join(basePath, projectCode);
  const planning = path.join(target, 'planning-artifacts');
  const impl = path.join(target, 'implementation-artifacts');
  const logs = path.join(target, 'logs');

  await fs.mkdir(planning, { recursive: true });
  await fs.mkdir(impl, { recursive: true });
  await fs.mkdir(logs, { recursive: true });

  return { target, planning, impl, logs, projectCode, artifactsRoot: basePath };
}

